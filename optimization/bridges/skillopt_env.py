"""Generate the environment adapter a native SkillOpt bundle needs to be runnable.

SkillOpt resolves `env.name` through a per-entry-point registry (`scripts.train._ENV_REGISTRY`, filled by
`_register_builtins()`), and the documented way to add a benchmark is to edit that function. A generated bundle
cannot edit an installed package, so it ships the adapter as a package of its own plus a small runner that registers
it in the registry *before* handing over to `scripts.train.main()` / `scripts.eval_only.main()`. The registry is only
ever added to, never cleared, so the injected class survives `_register_builtins()`.

The adapter follows the four-method contract in `docs/guide/new-benchmark.md`:

* a `SplitDataLoader` subclass that reads our `cases.jsonl` (`ratio` mode) or a split directory;
* a rollout that asks the configured target backend through `skillopt.model.chat_target` and scores the answer with
  the *same* rule as the run's `judge.py` (every `requires` token present, exact match when `expected` is set);
* an `EnvAdapter` subclass wiring those into `build_train_env` / `build_eval_env` / `rollout` / `get_task_types`;
* a persisted `predictions/<id>/conversation.json`, without which the inherited `reflect()` has nothing to learn
  from and the trainer reports `skip_no_patches`.

Nothing here imports SkillOpt at generation time: the strings are written into the bundle, which is what runs.
"""
from __future__ import annotations

import pathlib
import re
from string import Template

from .hermit import slug

PACKAGE = "env"
RUNNER = "run_skillopt.py"


def package_name(env_name: str) -> str:
    """A Python package name for the environment: `officeqa-skill` -> `officeqa_skill`."""
    name = re.sub(r"[^a-z0-9_]+", "_", env_name.lower()).strip("_")
    return name or "env"


def class_prefix(env_name: str) -> str:
    parts = [part for part in re.split(r"[^A-Za-z0-9]+", env_name) if part]
    return "".join(part[:1].upper() + part[1:] for part in parts) or "Bundle"


def files(spec, env_name: str | None = None) -> dict[str, str]:
    """Relative path -> text, for a bundle exporting this spec's cases."""
    env_name = env_name or slug(spec.name)
    package = package_name(env_name)
    prefix = class_prefix(env_name)
    return {
        f"{PACKAGE}/__init__.py": '"""The bundle\'s SkillOpt environment packages (generated)."""\n',
        f"{PACKAGE}/{package}/__init__.py": _INIT.substitute(prefix=prefix, package=package),
        f"{PACKAGE}/{package}/dataloader.py": _DATALOADER.substitute(prefix=prefix, env=env_name),
        f"{PACKAGE}/{package}/rollout.py": _ROLLOUT,
        f"{PACKAGE}/{package}/adapter.py": _ADAPTER.substitute(prefix=prefix, env=env_name),
        RUNNER: _RUNNER.substitute(prefix=prefix, env=env_name, package=package),
    }


def write(spec, out_dir: str | pathlib.Path, env_name: str | None = None) -> dict[str, pathlib.Path]:
    from .hermit import atomic_write_text

    out = pathlib.Path(out_dir)
    written: dict[str, pathlib.Path] = {}
    for relative, text in files(spec, env_name).items():
        path = out / relative
        atomic_write_text(path, text)
        written[relative] = path
    return written


_INIT = Template('''"""Environment adapter for `$package`, generated by `python -m optimization export`."""
from .adapter import ${prefix}Adapter
from .dataloader import ${prefix}DataLoader

__all__ = ["${prefix}Adapter", "${prefix}DataLoader"]
''')

_DATALOADER = Template('''"""Read the exported case rows into SkillOpt's item shape.

`split_mode: ratio` calls :meth:`load_raw_items` once and materializes its own deterministic split from
`env.data_path`; `split_mode: split_dir` calls :meth:`load_split_items` per split directory. Both paths accept a
JSON array or JSON Lines, because the bundle writes `.jsonl` and SkillOpt writes `.json`.
"""
from __future__ import annotations

import json
from pathlib import Path

from skillopt.datasets.base import SplitDataLoader


def read_rows(path: str | Path) -> list[dict]:
    """A JSON array, JSON Lines, or (for a directory) the one `.json`/`.jsonl` file inside it."""
    target = Path(path)
    if target.is_dir():
        candidates = sorted(target.glob("*.json")) + sorted(target.glob("*.jsonl"))
        if not candidates:
            raise FileNotFoundError(f"no .json or .jsonl file in {target}")
        target = candidates[0]
    text = target.read_text(encoding="utf-8")
    stripped = text.lstrip()
    if stripped.startswith("["):
        rows = json.loads(stripped)
    else:
        rows = [json.loads(line) for line in text.splitlines() if line.strip()]
    if not isinstance(rows, list):
        raise ValueError(f"{target} does not hold a list of case rows")
    return rows


def normalize(raw: dict) -> dict:
    """Our case row (`id`/`question`/`requires`/`expected`) as a SkillOpt item."""
    question = raw.get("question") or raw.get("input") or raw.get("prompt")
    if not isinstance(question, str) or not question.strip():
        raise ValueError(f"case {raw.get('id')!r} has no question text")
    requires = raw.get("requires") or []
    return {
        "id": str(raw.get("id") or raw.get("uid")),
        "question": question,
        "ground_truth": raw.get("expected"),
        "requires": [str(item) for item in requires],
        "task_type": str(raw.get("task_type") or "$env"),
        "reference_text": str(raw.get("reference_text") or ""),
    }


class ${prefix}DataLoader(SplitDataLoader):
    """The bundle's case rows, as SkillOpt items."""

    def load_raw_items(self, data_path: str) -> list[dict]:
        return [normalize(row) for row in read_rows(data_path)]

    def load_split_items(self, split_path: str) -> list[dict]:
        return [normalize(row) for row in read_rows(split_path)]
''')

_ROLLOUT = '''"""One target-model call per case, scored exactly as the run's `judge.py` scores it.

Scoring lives here, not in the adapter: `hard`/`soft` on each result dict is the only signal the optimizer reads.
The conversation is persisted under `predictions/<id>/conversation.json`, which the inherited `reflect()` reads.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

from skillopt.model import chat_target


def score_answer(prediction: str, item: dict) -> tuple[int, float]:
    """1 when every required token is present and (if given) the reference matches exactly."""
    text = (prediction or "").strip()
    expected = item.get("ground_truth")
    ok = all(str(token) in text for token in (item.get("requires") or []))
    if expected is not None:
        ok = ok and text == str(expected).strip()
    return (int(ok), 1.0 if ok else 0.0)


def _rollout_one(item: dict, skill_content: str, prediction_dir: Path,
                 max_completion_tokens: int) -> dict:
    system = skill_content or ""
    user = f"Question: {item['question']}\\n\\nAnswer:"
    try:
        prediction, _usage = chat_target(
            system=system, user=user, max_completion_tokens=max_completion_tokens,
        )
        error = None
    except Exception as exc:                       # a failed call is a failed case, not a dead run
        prediction, error = "", f"{type(exc).__name__}: {exc}"
    hard, soft = score_answer(prediction, item)

    task_dir = prediction_dir / str(item["id"])
    task_dir.mkdir(parents=True, exist_ok=True)
    conversation = [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
        {"role": "assistant", "content": prediction},
    ]
    (task_dir / "conversation.json").write_text(
        json.dumps(conversation, ensure_ascii=False, indent=2), encoding="utf-8")

    result = {
        "id": str(item["id"]),
        "hard": hard,
        "soft": soft,
        "predicted_answer": prediction,
        "task_description": item.get("question", ""),
        "question": item.get("question", ""),
        "task_type": item.get("task_type", ""),
        "reference_text": item.get("reference_text", ""),
        "target_system_prompt": system,
        "target_user_prompt": user,
        "n_turns": 1,
    }
    if error:
        result["error"] = error
        result["fail_reason"] = error
    return result


def run_batch(*, items: list[dict], skill_content: str, out_root: str,
              workers: int = 4, max_completion_tokens: int = 4096) -> list[dict]:
    """Roll out every item and write `rollouts.json` beside the conversations."""
    os.makedirs(out_root, exist_ok=True)
    prediction_dir = Path(out_root) / "predictions"
    results = [
        _rollout_one(item, skill_content, prediction_dir, max_completion_tokens)
        for item in items
    ]
    (Path(out_root) / "rollouts.json").write_text(
        json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    return results
'''

_ADAPTER = Template('''"""SkillOpt `EnvAdapter` for the exported cases (docs/guide/new-benchmark.md)."""
from __future__ import annotations

from skillopt.envs.base import EnvAdapter

from .dataloader import ${prefix}DataLoader
from .rollout import run_batch


class ${prefix}Adapter(EnvAdapter):
    """Wires the bundle's loader and rollout into SkillOpt's lifecycle."""

    def __init__(self, split_dir: str = "", data_path: str = "", split_mode: str = "ratio",
                 split_ratio: str = "2:1:7", split_seed: int = 42, split_output_dir: str = "",
                 workers: int = 4, analyst_workers: int = 4, failure_only: bool = False,
                 minibatch_size: int = 8, edit_budget: int = 4, seed: int = 42, limit: int = 0,
                 max_completion_tokens: int = 4096, **_ignored) -> None:
        self.env_name = "$env"
        self.workers = int(workers)
        self.analyst_workers = int(analyst_workers)
        self.failure_only = bool(failure_only)
        self.minibatch_size = int(minibatch_size)
        self.edit_budget = int(edit_budget)
        self.max_completion_tokens = int(max_completion_tokens)
        self.dataloader = ${prefix}DataLoader(
            split_dir=split_dir, data_path=data_path, split_mode=split_mode,
            split_ratio=split_ratio, split_seed=split_seed,
            split_output_dir=split_output_dir, seed=seed, limit=limit,
        )

    def setup(self, cfg: dict) -> None:
        super().setup(cfg)
        self.dataloader.setup(cfg)

    def get_dataloader(self):
        return self.dataloader

    def build_env_from_batch(self, batch, **_kwargs):
        return list(batch.payload or [])

    def build_train_env(self, batch_size: int, seed: int, **kwargs):
        batch = self.dataloader.build_train_batch(batch_size=batch_size, seed=seed, **kwargs)
        return self.build_env_from_batch(batch, **kwargs)

    def build_eval_env(self, env_num: int, split: str, seed: int, **kwargs):
        batch = self.dataloader.build_eval_batch(env_num=env_num, split=split, seed=seed, **kwargs)
        return self.build_env_from_batch(batch, **kwargs)

    def rollout(self, env_manager, skill_content: str, out_dir: str, **kwargs) -> list[dict]:
        return run_batch(
            items=list(env_manager), skill_content=skill_content, out_root=out_dir,
            workers=self.workers, max_completion_tokens=self.max_completion_tokens,
        )

    def get_task_types(self) -> list[str]:
        seen: list[str] = []
        for item in (*self.dataloader.train_items, *self.dataloader.val_items,
                     *self.dataloader.test_items):
            task_type = str(item.get("task_type") or self.env_name)
            if task_type not in seen:
                seen.append(task_type)
        return seen or [self.env_name]
''')

_RUNNER = Template('''"""Run SkillOpt with this bundle's environment adapter registered.

    python run_skillopt.py train --config skillopt.yaml
    python run_skillopt.py eval  --config skillopt.yaml --skill best_skill.md --split valid_unseen

SkillOpt resolves `env.name` through `scripts.train._ENV_REGISTRY` (filled by `_register_builtins()`). The registry
is only added to, never cleared, so registering the bundle's adapter before calling `main()` is enough; no file of
the installed package is edited. Everything after the mode is passed through unchanged.
"""
from __future__ import annotations

import sys
from pathlib import Path

BUNDLE = Path(__file__).resolve().parent
if str(BUNDLE) not in sys.path:
    sys.path.insert(0, str(BUNDLE))

from env.$package.adapter import ${prefix}Adapter  # noqa: E402

ENV_NAME = "$env"
USAGE = __doc__.strip().splitlines()[0]


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] not in ("train", "eval"):
        print("usage: python run_skillopt.py {train|eval} --config skillopt.yaml ...")
        print(USAGE)
        return 2
    mode, rest = argv[0], argv[1:]
    if mode == "train":
        from scripts import train as entry
        entry._ENV_REGISTRY[ENV_NAME] = ${prefix}Adapter
        sys.argv = ["skillopt-train", *rest]
        entry.main()
    else:
        from scripts import eval_only as entry
        entry._ENV_REGISTRY[ENV_NAME] = ${prefix}Adapter
        sys.argv = ["skillopt-eval", *rest]
        entry.main()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
''')
