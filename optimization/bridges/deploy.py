"""Workspace deployment, following ``hermit deploy``'s documented contract.

Hermit deploys an adapter into an empty (or previously generated) workspace and
connects its exports there. For a context-only adapter — the case this kernel
produces — the observable result is:

    <workspace>/AGENTS.md            Codex and Pi
    <workspace>/CLAUDE.md            Claude Code
    <workspace>/hermit/<id>/...      the adapter's files

The instruction file gets a *managed block*: a marked region naming
``hermit/<id>/`` and carrying the adapter text. Redeploying replaces that block
instead of appending a second copy, and an arbitrary non-empty project is
refused — both behaviours the docs call out.

``convert`` (native plugin emission) is deliberately not reimplemented here:
``hermit convert --adapter adapter --target ...`` is Hermit's own job, and
faking a plugin format would be more likely to mislead than to help. The export
ships a loadable adapter directory, which is exactly what ``convert`` consumes.
"""
from __future__ import annotations

import json
import pathlib
import re
import shutil

from .._io import atomic_write_text, read_json

HOST_FILES = {"codex": "AGENTS.md", "claude-code": "CLAUDE.md", "pi": "AGENTS.md"}
MARKER = ".hermit-deploy.json"
CODEX_CONTEXT_LIMIT = 32768


class DeployError(RuntimeError):
    """The workspace or adapter cannot be deployed as asked."""


def _adapter_identity(adapter: pathlib.Path) -> tuple[str, str]:
    manifest = adapter / ".hermit" / "adapter.yaml"
    if not manifest.is_file():
        raise DeployError(f"{adapter} has no .hermit/adapter.yaml")
    text = manifest.read_text(encoding="utf-8")
    ident = re.search(r"id:\s*(\S+)", text)
    version = re.search(r'version:\s*"?([^"\n]+)"?', text)
    if not ident:
        raise DeployError("adapter.yaml has no template.id")
    return ident.group(1), (version.group(1) if version else "unknown")


def _managed_block(adapter_id: str, context: str) -> str:
    return "\n".join([
        f"<!-- hermit:begin {adapter_id} -->",
        f"# Harness adapter `{adapter_id}`",
        "",
        f"The adapter's files are in `hermit/{adapter_id}/`.",
        "",
        context.strip(),
        f"<!-- hermit:end {adapter_id} -->",
    ])


def deploy(adapter_dir: str | pathlib.Path, workspace: str | pathlib.Path,
           host: str, context_limit: int = CODEX_CONTEXT_LIMIT) -> dict[str, object]:
    adapter = pathlib.Path(adapter_dir)
    workspace = pathlib.Path(workspace)
    if host not in HOST_FILES:
        raise DeployError(f"unknown host {host!r}; expected {sorted(HOST_FILES)}")
    try:
        adapter.resolve().relative_to(workspace.resolve())
    except ValueError:
        pass
    else:
        raise DeployError(
            "the workspace must be separate from the adapter directory; "
            "deploying into it would replace the source"
        )
    context_path = adapter / "ADAPTER.md"
    if not context_path.is_file():
        raise DeployError(f"{adapter} has no ADAPTER.md")
    context = context_path.read_text(encoding="utf-8")
    if host == "codex" and context_limit and len(context) > context_limit:
        raise DeployError(
            f"context is {len(context)} bytes > Codex project_doc_max_bytes "
            f"{context_limit}; raise the limit or shorten the adapter"
        )
    adapter_id, version = _adapter_identity(adapter)

    marker_path = workspace / MARKER
    generated = marker_path.is_file()
    if workspace.exists() and any(workspace.iterdir()) and not generated:
        raise DeployError(
            f"{workspace} is not empty and was not generated by this tool; "
            "use an empty directory or a previously generated workspace"
        )
    if generated and read_json(marker_path).get("host") != host:
        raise DeployError(
            f"{workspace} was generated for host "
            f"{read_json(marker_path).get('host')!r}, not {host!r}"
        )

    target = workspace / "hermit" / adapter_id
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(adapter, target)

    instruction = workspace / HOST_FILES[host]
    block = _managed_block(adapter_id, context)
    if instruction.is_file():
        text = instruction.read_text(encoding="utf-8")
        pattern = re.compile(
            rf"<!-- hermit:begin {re.escape(adapter_id)} -->.*?"
            rf"<!-- hermit:end {re.escape(adapter_id)} -->",
            re.DOTALL,
        )
        text = pattern.sub(block, text) if pattern.search(text) else \
            text.rstrip() + "\n\n" + block + "\n"
    else:
        text = block + "\n"
    atomic_write_text(instruction, text)

    marker = {
        "host": host, "adapter_id": adapter_id, "version": version,
        "instruction_file": HOST_FILES[host],
        "adapter_dir": f"hermit/{adapter_id}",
    }
    atomic_write_text(marker_path, json.dumps(marker, indent=2, sort_keys=True) + "\n")
    return marker


def validate(workspace: str | pathlib.Path, host: str) -> list[str]:
    workspace = pathlib.Path(workspace)
    problems: list[str] = []
    if host not in HOST_FILES:
        return [f"unknown host {host!r}"]
    marker_path = workspace / MARKER
    if not marker_path.is_file():
        return [f"missing {MARKER}"]
    marker = json.loads(marker_path.read_text(encoding="utf-8"))
    if marker.get("host") != host:
        problems.append(f"workspace was generated for {marker.get('host')!r}")
    instruction = workspace / HOST_FILES[host]
    if not instruction.is_file():
        problems.append(f"missing {HOST_FILES[host]}")
    else:
        text = instruction.read_text(encoding="utf-8")
        begin = text.count(f"hermit:begin {marker.get('adapter_id')}")
        end = text.count(f"hermit:end {marker.get('adapter_id')}")
        if begin != 1 or end != 1:
            problems.append(
                f"{HOST_FILES[host]} has {begin} begin / {end} end markers "
                "(exactly one managed block expected)"
            )
        if f"hermit/{marker.get('adapter_id')}/" not in text:
            problems.append(f"{HOST_FILES[host]} does not name hermit/<id>/")
    copied = workspace / str(marker.get("adapter_dir", "")) / "ADAPTER.md"
    if not copied.is_file():
        problems.append("the adapter was not copied into hermit/<id>/")
    elif copied.read_text(encoding="utf-8") != \
            (workspace / "hermit" / str(marker.get("adapter_id")) / "ADAPTER.md"
             ).read_text(encoding="utf-8"):
        problems.append("copied ADAPTER.md is not readable")
    return problems
